/** 공휴일 이름 (아니면 null) */
export function holidayName(date: DateStr): string | null {
  return HOLIDAYS[date] ?? null;
}

/** 달력 칸에 들어갈 짧은 이름 */
export function shortHolidayName(name: string): string {
  if (name === "대체공휴일" || name === "임시공휴일") return name.replace("공휴일", "휴일");
  if (name.endsWith(" 연휴")) return name.replace(" 연휴", "");
  return name.split("·")[0];
}
